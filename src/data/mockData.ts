function buildFingerprint(inv: Partial<Invoice>): string {
  const canonical = createCanonicalInvoicePayload({
    invoiceNumber: inv.invoiceNumber || '',
    issueDate: inv.issueDate || '',
    dueDate: inv.dueDate || '',
    currency: inv.currency || 'USD',
    total: inv.financials?.total || 0,
    issuerId: inv.issuer?.id || '',
    issuerName: inv.issuer?.name || '',
    buyerName: inv.buyer?.name || '',
    itemsCount: inv.items?.length || 0,
  });
  return computeSha256FingerprintSync(canonical);
}

